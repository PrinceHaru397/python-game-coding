# Define the tuple
t = (100, 200, 300, 400, 500, 600, 700, 800, 900, 1000)

# Print the tuple
print(t)

# Print all the values
for i in t:
    print(i)

# Define the nested tuple
matrix = ((1, 2, 3), (4, 5, 6), (7, 8, 9))

# Print the nested tuple
print(matrix)

# Print all the values
for i in matrix:
    for j in i:
        print(j)
